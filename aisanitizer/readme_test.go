package aisanitizer

import (
	"os"
	"strings"
	"testing"
)

const (
	rulesStart = "<!-- rules:start (generated by `go test ./aisanitizer -run TestReadmeRules -update`) -->"
	rulesEnd   = "<!-- rules:end -->"
)

// rulesMarkdown renders the rule registry as a Markdown table.
func rulesMarkdown() string {
	var b strings.Builder
	b.WriteString("| Rule | Category | Action | Default | Option | Description |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, r := range Rules() {
		def := "off"
		if r.Default {
			def = "**on**"
		}
		opt := ""
		if r.Option != "" {
			opt = "`" + r.Option + "`"
		}
		desc := strings.ReplaceAll(r.Description, "|", `\|`)
		b.WriteString("| `" + string(r.ID) + "` | " + r.Category + " | " + string(r.Action) + " | " + def + " | " + opt + " | " + desc + " |\n")
	}
	return b.String()
}

// TestReadmeRules keeps the README rules table in sync with the registry.
func TestReadmeRules(t *testing.T) {
	const path = "../README.md"
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	readme := string(data)
	i, j := strings.Index(readme, rulesStart), strings.Index(readme, rulesEnd)
	if i < 0 || j < i {
		t.Fatal("README.md is missing the rules markers")
	}
	want := readme[:i+len(rulesStart)] + "\n\n" + rulesMarkdown() + "\n" + readme[j:]
	if want == readme {
		return
	}
	if *update {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	t.Error("README.md rules table is stale; run: go test ./aisanitizer -run TestReadmeRules -update")
}
