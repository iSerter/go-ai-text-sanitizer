func charNames(ud *unicodeData, di []rune, confusables [][2]rune) []runeString {
	want := map[rune]bool{}
	for _, r := range di {
		// Tags and variation selectors are named algorithmically.
		if (r >= 0xE0000 && r <= 0xE007F) || (r >= 0xFE00 && r <= 0xFE0F) || (r >= 0xE0100 && r <= 0xE01EF) {
			continue
		}
		want[r] = true
	}
	for _, r := range extraNamed {
		want[r] = true
	}
	for r := rune(0x13430); r <= 0x13440; r++ {
		want[r] = true
	}
	for _, p := range confusables {
		want[p[0]] = true
	}
	var out []runeString
	for r := range want {
		c := ud.byRune[r]
		if c == nil || c.name == "" || strings.HasPrefix(c.name, "<") {
			continue
		}
		out = append(out, runeString{r, c.name})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].r < out[j].r })
	return out
}

func writeTable(b *bytes.Buffer, name, doc string, runes []rune) {
	sort.Slice(runes, func(i, j int) bool { return runes[i] < runes[j] })
	type rng struct{ lo, hi rune }
	var ranges []rng
	for _, r := range runes {
		if n := len(ranges); n > 0 && (ranges[n-1].hi == r || ranges[n-1].hi+1 == r) {
			ranges[n-1].hi = r
			continue
		}
		ranges = append(ranges, rng{r, r})
	}
	fmt.Fprintf(b, "// %s: %s\n", name, doc)
	fmt.Fprintf(b, "var %s = &unicode.RangeTable{\n", name)
	var r16, r32 []rng
	latin := 0
	for _, r := range ranges {
		switch {
		case r.hi <= 0xFFFF:
			r16 = append(r16, r)
			if r.hi <= unicode.MaxLatin1 {
				latin++
			}
		case r.lo > 0xFFFF:
			r32 = append(r32, r)
		default:
			r16 = append(r16, rng{r.lo, 0xFFFF})
			r32 = append(r32, rng{0x10000, r.hi})
		}
	}
	if len(r16) > 0 {
		b.WriteString("\tR16: []unicode.Range16{\n")
		for _, r := range r16 {
			fmt.Fprintf(b, "\t\t{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", r.lo, r.hi)
		}
		b.WriteString("\t},\n")
	}
	if len(r32) > 0 {
		b.WriteString("\tR32: []unicode.Range32{\n")
		for _, r := range r32 {
			fmt.Fprintf(b, "\t\t{Lo: 0x%X, Hi: 0x%X, Stride: 1},\n", r.lo, r.hi)
		}
		b.WriteString("\t},\n")
	}
	if latin > 0 {
		fmt.Fprintf(b, "\tLatinOffset: %d,\n", latin)
	}
	b.WriteString("}\n\n")
}
