// Command ucdgen generates the Unicode lookup tables used by package
// aisanitizer from the official Unicode Character Database files.
//
// It is run via `go generate ./aisanitizer` and needs network access (or a
// warm cache directory). The generated code has no dependencies beyond the Go
// standard library, so the aisanitizer package stays zero-dependency.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

var (
	version  = flag.String("unicode", "18.0.0", "Unicode version to generate tables for")
	cacheDir = flag.String("cache", filepath.Join(os.TempDir(), "ucdgen-cache"), "download cache directory")
	outFile  = flag.String("out", "tables_gen.go", "output Go file")
	emojiOut = flag.String("emoji-testdata", "testdata/emoji-fully-qualified.txt", "output file for fully-qualified emoji sequences")
)

func main() {
	flag.Parse()
	log.SetFlags(0)
	log.SetPrefix("ucdgen: ")

	ud := parseUnicodeData(fetch("ucd/UnicodeData.txt"))
	di := parseProperty(fetch("ucd/DerivedCoreProperties.txt"), "Default_Ignorable_Code_Point")
	ideo := parseProperty(fetch("ucd/PropList.txt"), "Ideographic")
	emojiData := fetch("ucd/emoji/emoji-data.txt")
	extPict := parseProperty(emojiData, "Extended_Pictographic")
	emoji := parseProperty(emojiData, "Emoji")
	joining := parseJoiningTypes(fetch("ucd/extracted/DerivedJoiningType.txt"))
	variants := parseVariants(fetch("ucd/StandardizedVariants.txt"), fetch("ucd/emoji/emoji-variation-sequences.txt"))
	confusables := parseConfusables(fetch("security/confusables.txt"))
	emojiSeqs := parseEmojiTest(fetch("emoji/emoji-test.txt"))

	var virama, rtl []rune
	for _, c := range ud.chars {
		if c.ccc == "9" {
			virama = append(virama, c.r)
		}
		if c.bidi == "R" || c.bidi == "AL" {
			rtl = append(rtl, c.r)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/ucdgen from the Unicode %s data files; DO NOT EDIT.\n\n", *version)
	b.WriteString("package aisanitizer\n\nimport \"unicode\"\n\n")
	fmt.Fprintf(&b, "// UnicodeVersion is the version of the Unicode Character Database the\n// sanitizer's character tables were generated from.\nconst UnicodeVersion = %q\n\n", *version)

	writeTable(&b, "tblDefaultIgnorable", "Default_Ignorable_Code_Point (DerivedCoreProperties.txt).", di)
	writeTable(&b, "tblExtPict", "Extended_Pictographic (emoji-data.txt).", extPict)
	writeTable(&b, "tblEmoji", "Emoji (emoji-data.txt).", emoji)
	writeTable(&b, "tblVirama", "Canonical_Combining_Class=Virama (UnicodeData.txt).", virama)
	writeTable(&b, "tblRTL", "Bidi_Class R or AL (UnicodeData.txt).", rtl)
	writeTable(&b, "tblIdeographic", "Ideographic (PropList.txt).", ideo)
	writeTable(&b, "tblJoinL", "Joining_Type=L (DerivedJoiningType.txt).", joining["L"])
	writeTable(&b, "tblJoinD", "Joining_Type=D or C (DerivedJoiningType.txt).", append(joining["D"], joining["C"]...))
	writeTable(&b, "tblJoinR", "Joining_Type=R (DerivedJoiningType.txt).", joining["R"])
	writeTable(&b, "tblJoinT", "Joining_Type=T (DerivedJoiningType.txt).", joining["T"])

	b.WriteString("// stdVariants lists the registered (base, variation selector) pairs from\n// StandardizedVariants.txt and emoji-variation-sequences.txt, sorted.\n")
	b.WriteString("var stdVariants = [...]runePair{\n")
	for _, p := range variants {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", p[0], p[1])
	}
	b.WriteString("}\n\n")

	b.WriteString("// confusableLatin maps non-Latin letters (Cyrillic, Greek, Armenian,\n// Cherokee, Coptic, Lisu) to the single ASCII letter or digit they are\n// visually confusable with (UTS #39 confusables.txt), sorted.\n")
	b.WriteString("var confusableLatin = [...]runePair{\n")
	for _, p := range confusables {
		fmt.Fprintf(&b, "\t{0x%04X, '%c'},\n", p[0], p[1])
	}
	b.WriteString("}\n\n")

	fold := compatFold(ud, di)
	b.WriteString("// compatFoldTable holds compatibility decompositions (<compat>, <font>,\n// <wide>, <narrow>, <super>, <sub>, <circle>, <fraction>, <small>,\n// <square>, <vertical> and Arabic positional forms), applied recursively and\n// filtered so that no target contains combining marks, default-ignorable\n// characters or conjoining jamo. Sorted by rune.\n")
	b.WriteString("var compatFoldTable = [...]runeString{\n")
	for _, f := range fold {
		fmt.Fprintf(&b, "\t{0x%04X, %q},\n", f.r, f.s)
	}
	b.WriteString("}\n\n")

	names := charNames(ud, di, confusables)
	b.WriteString("// charNameTable holds Unicode character names for the code points the\n// sanitizer reports on, sorted by rune.\n")
	b.WriteString("var charNameTable = [...]runeString{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t{0x%04X, %q},\n", n.r, n.s)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("formatting generated code: %v", err)
	}
	if err := os.WriteFile(*outFile, src, 0o644); err != nil {
		log.Fatal(err)
	}

	if *emojiOut != "" {
		var e strings.Builder
		fmt.Fprintf(&e, "# Fully-qualified emoji sequences from Unicode %s emoji-test.txt.\n# Generated by internal/ucdgen; DO NOT EDIT.\n", *version)
		for _, s := range emojiSeqs {
			e.WriteString(s)
			e.WriteByte('\n')
		}
		if err := os.MkdirAll(filepath.Dir(*emojiOut), 0o755); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(*emojiOut, []byte(e.String()), 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

func fetch(path string) []byte {
	local := filepath.Join(*cacheDir, *version, filepath.FromSlash(path))
	if data, err := os.ReadFile(local); err == nil {
		return data
	}
	url := "https://www.unicode.org/Public/" + *version + "/" + path
	log.Printf("downloading %s", url)
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(local), 0o755); err == nil {
		_ = os.WriteFile(local, data, 0o644)
	}
	return data
}

// lines yields the data fields of a UCD-style file (comments stripped).
func lines(data []byte, fn func(fields []string, comment string)) {
	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		comment := ""
		if i := strings.IndexByte(line, '#'); i >= 0 {
			comment = strings.TrimSpace(line[i+1:])
			line = line[:i]
		}
		if strings.TrimSpace(line) == "" {
			continue
		}
		fields := strings.Split(line, ";")
		for i := range fields {
			fields[i] = strings.TrimSpace(fields[i])
		}
		fn(fields, comment)
	}
}

func parseHex(s string) rune {
	v, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		log.Fatalf("bad code point %q: %v", s, err)
	}
	return rune(v)
}

func parseRange(s string) (lo, hi rune) {
	if a, b, ok := strings.Cut(s, ".."); ok {
		return parseHex(a), parseHex(b)
	}
	r := parseHex(s)
	return r, r
}

func parseProperty(data []byte, prop string) []rune {
	var out []rune
	lines(data, func(f []string, _ string) {
		if len(f) >= 2 && f[1] == prop {
			lo, hi := parseRange(f[0])
			for r := lo; r <= hi; r++ {
				out = append(out, r)
			}
		}
	})
	return out
}

func parseJoiningTypes(data []byte) map[string][]rune {
	out := map[string][]rune{}
	lines(data, func(f []string, _ string) {
		lo, hi := parseRange(f[0])
		for r := lo; r <= hi; r++ {
			out[f[1]] = append(out[f[1]], r)
		}
	})
	return out
}

type udChar struct {
	r      rune
	name   string
	gc     string
	ccc    string
	bidi   string
	decomp string
}

type unicodeData struct {
	chars  []udChar
	byRune map[rune]*udChar
}

func parseUnicodeData(data []byte) *unicodeData {
	ud := &unicodeData{byRune: map[rune]*udChar{}}
	var rangeStart *udChar
	lines(data, func(f []string, _ string) {
		c := udChar{r: parseHex(f[0]), name: f[1], gc: f[2], ccc: f[3], bidi: f[4], decomp: f[5]}
		switch {
		case strings.HasSuffix(c.name, ", First>"):
			cc := c
			rangeStart = &cc
			return
		case strings.HasSuffix(c.name, ", Last>") && rangeStart != nil:
			for r := rangeStart.r; r <= c.r; r++ {
				cc := *rangeStart
				cc.r, cc.name = r, ""
				ud.chars = append(ud.chars, cc)
			}
			rangeStart = nil
			return
		}
		ud.chars = append(ud.chars, c)
	})
	for i := range ud.chars {
		ud.byRune[ud.chars[i].r] = &ud.chars[i]
	}
	return ud
}

func parseVariants(std, emoji []byte) [][2]rune {
	seen := map[[2]rune]bool{}
	var out [][2]rune
	add := func(f []string, _ string) {
		cps := strings.Fields(f[0])
		if len(cps) != 2 {
			return
		}
		p := [2]rune{parseHex(cps[0]), parseHex(cps[1])}
		if !seen[p] {
			seen[p] = true
			out = append(out, p)
		}
	}
	lines(std, add)
	lines(emoji, add)
	sort.Slice(out, func(i, j int) bool {
		if out[i][0] != out[j][0] {
			return out[i][0] < out[j][0]
		}
		return out[i][1] < out[j][1]
	})
	return out
}

var confusableScripts = []*unicode.RangeTable{
	unicode.Cyrillic, unicode.Greek, unicode.Armenian, unicode.Cherokee, unicode.Coptic, unicode.Lisu,
}

func parseConfusables(data []byte) [][2]rune {
	var out [][2]rune
	lines(data, func(f []string, _ string) {
		src := strings.Fields(f[0])
		dst := strings.Fields(f[1])
		if len(src) != 1 || len(dst) != 1 {
			return
		}
		s, d := parseHex(src[0]), parseHex(dst[0])
		if !unicode.IsLetter(s) || !unicode.IsOneOf(confusableScripts, s) {
			return
		}
		if !(d >= 'a' && d <= 'z' || d >= 'A' && d <= 'Z' || d >= '0' && d <= '9') {
			return
		}
		out = append(out, [2]rune{s, d})
	})
	sort.Slice(out, func(i, j int) bool { return out[i][0] < out[j][0] })
	return out
}

func parseEmojiTest(data []byte) []string {
	var out []string
	lines(data, func(f []string, _ string) {
		if len(f) < 2 || f[1] != "fully-qualified" {
			return
		}
		var sb strings.Builder
		for _, cp := range strings.Fields(f[0]) {
			sb.WriteRune(parseHex(cp))
		}
		out = append(out, sb.String())
	})
	return out
}

type runeString struct {
	r rune
	s string
}

var foldTags = map[string]bool{
	"<compat>": true, "<font>": true, "<wide>": true, "<narrow>": true, "<super>": true,
	"<sub>": true, "<circle>": true, "<fraction>": true, "<small>": true, "<square>": true,
	"<vertical>": true, "<initial>": true, "<medial>": true, "<final>": true, "<isolated>": true,
}

func compatFold(ud *unicodeData, di []rune) []runeString {
	ignorable := map[rune]bool{}
	for _, r := range di {
		ignorable[r] = true
	}
	var expand func(r rune, depth int) (string, bool)
	expand = func(r rune, depth int) (string, bool) {
		c := ud.byRune[r]
		if c == nil || depth > 8 {
			return string(r), false
		}
		fields := strings.Fields(c.decomp)
		if len(fields) == 0 || !foldTags[fields[0]] {
			return string(r), false
		}
		var sb strings.Builder
		for _, cp := range fields[1:] {
			t := parseHex(cp)
			if t == 0x2044 { // FRACTION SLASH
				t = '/'
			}
			s, _ := expand(t, depth+1)
			sb.WriteString(s)
		}
		return sb.String(), true
	}
	var out []runeString
	for _, c := range ud.chars {
		// Hangul compatibility jamo fold to conjoining jamo, which would
		// recombine with neighbouring syllables; never fold them.
		if c.r >= 0x3131 && c.r <= 0x318E {
			continue
		}
		s, ok := expand(c.r, 0)
		if !ok || s == "" {
			continue
		}
		valid := true
		for _, t := range s {
			if unicode.Is(unicode.M, t) || ignorable[t] || (t >= 0x1100 && t <= 0x11FF) || unicode.IsControl(t) {
				valid = false
				break
			}
		}
		if !valid || strings.TrimSpace(s) == "" {
			continue
		}
		out = append(out, runeString{c.r, s})
	}
	return out
}

